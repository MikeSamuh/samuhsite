// Builds the process figure data from scripts/figures/traced.json.
// Writes src/components/process-figure/figures.ts and morphs.ts.
// Run from the repo root after trace.py. The two packages are only needed to
// regenerate, so they are not dependencies of the site:
//
//   npm i --no-save flubber@0.4.2 svg-path-properties
//   node scripts/figures/build-morphs.mjs
//
// Matching: heads (circularity above 0.95) pair with heads, the other shapes
// pair greedily by centroid distance plus size difference, and a shape with no
// partner grows from or shrinks to a point at its own centre.
import fs from 'fs';
const OUT = 'src/components/process-figure';
import flubber from 'flubber';
import { svgPathProperties } from 'svg-path-properties';
const POSES = JSON.parse(fs.readFileSync('scripts/figures/traced.json','utf8'));
const r1 = n => Math.round(n*10)/10;
function measure(d){
  const p = new svgPathProperties(d), L = p.getTotalLength(), n = 120, pts = [];
  for (let i=0;i<n;i++){ const q=p.getPointAtLength(L*i/n); pts.push([q.x,q.y]); }
  let A=0,cx=0,cy=0;
  for (let i=0;i<n;i++){const [x0,y0]=pts[i],[x1,y1]=pts[(i+1)%n],c=x0*y1-x1*y0;A+=c;cx+=(x0+x1)*c;cy+=(y0+y1)*c;}
  A/=2;cx/=6*A;cy/=6*A;A=Math.abs(A);
  const xs=pts.map(p=>p[0]);
  return {d,area:A,cx,cy,circ:4*Math.PI*A/(L*L),bw:Math.max(...xs)-Math.min(...xs)};
}
const shapes = {};
for (const [k,list] of Object.entries(POSES)) {
  shapes[k] = list.map(measure).filter(s=>s.bw<490 && s.area>250);
  shapes[k].forEach(s=>s.head = s.circ>0.95);
  console.log(k, shapes[k].map(s=>[s.head?'H':'-', Math.round(s.area), s.circ.toFixed(2)].join('')).join(' '));
}
const dot=(cx,cy)=>Array.from({length:12},(_,i)=>{const t=i/12*Math.PI*2;return [cx+.6*Math.cos(t),cy+.6*Math.sin(t)];});
function pair(A,B){
  const cand=[];
  A.forEach((a,i)=>B.forEach((b,j)=>{ if(a.head!==b.head) return;
    cand.push([Math.hypot(a.cx-b.cx,a.cy-b.cy)+0.6*Math.abs(Math.sqrt(a.area)-Math.sqrt(b.area)),i,j]);}));
  cand.sort((x,y)=>x[0]-y[0]);
  const ua=new Set(),ub=new Set(),out=[];
  for (const [,i,j] of cand){ if(ua.has(i)||ub.has(j)) continue; ua.add(i);ub.add(j); out.push([A[i],B[j]]); }
  A.forEach((a,i)=>{ if(!ua.has(i)) out.push([a,null]); });
  B.forEach((b,j)=>{ if(!ub.has(j)) out.push([null,b]); });
  return out.map(([a,b])=>{
    const f = flubber.interpolate(a?a.d:dot(b.cx,b.cy), b?b.d:dot(a.cx,a.cy), {string:false, maxSegmentLength:6});
    const s=f(0), e=f(1); if (s.length!==e.length) throw new Error('len');
    return { head: (a||b).head, from: s.flat().map(r1), to: e.flat().map(r1) };
  });
}
// each stage morphs out of the one before it, in STAGES order
const ids = Object.keys(shapes), morphs = {};
for (let i = 1; i < ids.length; i++) morphs[`${ids[i-1]}>${ids[i]}`] = pair(shapes[ids[i-1]], shapes[ids[i]]);
const hdr = '// GENERATED by scripts/figures/build-morphs.mjs. Do not edit by hand.\n';
fs.writeFileSync(OUT+'/figures.ts', hdr +
`// Rest poses for the process stages, traced from public/icons. 512 x 512 viewBox.
export const POSES = {
${Object.entries(shapes).map(([k,l])=>`  ${k}: ${JSON.stringify(l.map(s=>s.d))},`).join('\n')}
} as const;

export type PoseId = keyof typeof POSES;
`);
fs.writeFileSync(OUT+'/morphs.ts', hdr +
`// Point-matched rings for each stage-to-stage morph. Each part is a flat
// [x0, y0, x1, y1, ...] ring; "from" and "to" have the same length, so a morph is
// a straight lerp. Heads are flagged so they can lead the body.
export type MorphPart = { head: boolean; from: number[]; to: number[] };

export const MORPHS: Record<string, MorphPart[]> = ${JSON.stringify(morphs)};
`);
for (const f of ['figures.ts','morphs.ts']) console.log(f, fs.statSync(OUT+'/'+f).size, 'bytes');
